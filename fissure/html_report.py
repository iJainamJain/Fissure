"""Render a scan report dict into a single self-contained HTML file."""

from __future__ import annotations

import html
from pathlib import Path
from typing import Any

_SEV_COLOR = {
    "critical": "#b00020", "high": "#d9480f", "medium": "#e8590c",
    "low": "#2b8a3e", "info": "#495057",
}
_LABEL_COLOR = {
    "CRITICAL": "#b00020", "HIGH": "#d9480f", "MEDIUM": "#e8590c",
    "LOW": "#2b8a3e", "CLEAN": "#2b8a3e",
}


def generate_html_report(report: dict[str, Any], output_path: str) -> str:
    s = report["summary"]
    t = report["target"]
    label = s["label"]
    rows = []
    for mod_name, mod in report["modules"].items():
        rows.append(_module_section(mod_name, mod))
    modules_html = "\n".join(rows)

    doc = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Fissure Report — {html.escape(t['hostname'])}</title>
<style>
  :root {{ color-scheme: light dark; }}
  body {{ font-family: system-ui, -apple-system, Segoe UI, Roboto, sans-serif; margin: 0; background:#f6f7f9; color:#1a1a1a; }}
  header {{ background:#12233b; color:#fff; padding:24px 32px; }}
  header h1 {{ margin:0 0 4px; font-size:22px; }}
  header .sub {{ opacity:.8; font-size:13px; }}
  .wrap {{ max-width: 960px; margin: 0 auto; padding: 24px 16px; }}
  .cards {{ display:flex; gap:12px; flex-wrap:wrap; margin-bottom:24px; }}
  .card {{ background:#fff; border:1px solid #e3e6ea; border-radius:10px; padding:16px 20px; flex:1 1 140px; }}
  .card .n {{ font-size:26px; font-weight:700; }}
  .card .l {{ font-size:12px; text-transform:uppercase; letter-spacing:.04em; color:#667; }}
  .badge {{ display:inline-block; padding:4px 12px; border-radius:999px; color:#fff; font-weight:700; font-size:13px; background:{_LABEL_COLOR.get(label,'#495057')}; }}
  .mod {{ background:#fff; border:1px solid #e3e6ea; border-radius:10px; margin-bottom:16px; overflow:hidden; }}
  .mod h2 {{ margin:0; padding:14px 18px; font-size:15px; background:#eef1f5; }}
  .mod .body {{ padding:8px 18px 16px; }}
  .finding {{ border-left:4px solid #ccc; padding:10px 14px; margin:10px 0; background:#fafbfc; border-radius:4px; }}
  .finding .title {{ font-weight:600; }}
  .sev {{ display:inline-block; font-size:11px; text-transform:uppercase; font-weight:700; color:#fff; padding:2px 8px; border-radius:4px; margin-right:8px; }}
  .loc {{ font-family: ui-monospace, Menlo, monospace; font-size:12px; color:#556; word-break:break-all; }}
  .ev {{ font-size:13px; margin-top:4px; }}
  .heur {{ font-size:11px; color:#a15c00; }}
  .none {{ color:#2b8a3e; font-size:13px; }}
  footer {{ text-align:center; font-size:12px; color:#889; padding:20px; }}
</style></head><body>
<header>
  <h1>Fissure — Active Web Vulnerability Report</h1>
  <div class="sub">{html.escape(t['base_url'])} · scope: {html.escape(t['scope'])} · generated {html.escape(report['created_at'])}</div>
</header>
<div class="wrap">
  <div class="cards">
    <div class="card"><div class="n"><span class="badge">{label}</span></div><div class="l">Risk label</div></div>
    <div class="card"><div class="n">{s['score']}</div><div class="l">Risk score</div></div>
    <div class="card"><div class="n">{s['total_findings']}</div><div class="l">Findings</div></div>
    <div class="card"><div class="n">{s['injectables_found']}</div><div class="l">Injectable inputs</div></div>
    <div class="card"><div class="n">{s['endpoints_crawled']}</div><div class="l">Endpoints crawled</div></div>
  </div>
  {modules_html}
</div>
<footer>Generated by Fissure v{html.escape(report['tool']['version'])} · authorized lab use only</footer>
</body></html>"""

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(doc, encoding="utf-8")
    return str(path)


def _module_section(name: str, mod: dict[str, Any]) -> str:
    findings = mod["findings"]
    if findings:
        items = "\n".join(_finding_html(f) for f in findings)
    else:
        items = f'<div class="none">✔ {html.escape(mod["summary"])}</div>'
    return f"""<div class="mod">
  <h2>{html.escape(name)} — {html.escape(mod['status'])} · {mod['risk_points']} pts</h2>
  <div class="body">{items}</div>
</div>"""


def _finding_html(f: dict[str, Any]) -> str:
    color = _SEV_COLOR.get(f["severity"].lower(), "#495057")
    heur = "" if f["confirmed"] else '<div class="heur">⚑ heuristic — confirm manually</div>'
    return f"""<div class="finding" style="border-left-color:{color}">
    <div class="title"><span class="sev" style="background:{color}">{html.escape(f['severity'])}</span>{html.escape(f['title'])}</div>
    <div class="loc">{html.escape(f['location'])}</div>
    <div class="ev">{html.escape(f['evidence'])}</div>
    {heur}
  </div>"""
